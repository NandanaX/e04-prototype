export function t(lang: Language) {
  return STRINGS[lang]
}

export function formatCurrency(amount: number, lang: Language) {
  return new Intl.NumberFormat(lang === "ar" ? "ar-AE" : "en-US", {
    style: "currency",
    currency: "USD",
    currencyDisplay: "narrowSymbol",
    maximumFractionDigits: 0,
  }).format(amount)
}

export function formatDate(iso: string, lang: Language) {
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-AE" : "en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  }).format(new Date(iso))
}
